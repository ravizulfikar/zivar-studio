const assert = require('node:assert/strict')
const { planDdl, formatDdl } = require('./.build/ddl.cjs')

let n = 0
const col = (name, type, o = {}) => ({ id: name + (++n), originalName: o.isNew ? null : name, name, type, nullable: true, primaryKey: false, defaultValue: null, autoIncrement: false, ...o })
const idx = (name, columns, o = {}) => ({ id: name + (++n), originalName: o.isNew ? null : name, name, columns, unique: false, ...o })
const ctx = (kind) => ({ kind, container: kind === 'sqlite' ? 'main' : 'app', schema: 'dbo' })
const clone = (d) => JSON.parse(JSON.stringify(d))
const run = (kind, o, e) => planDdl(ctx(kind), o, e)
const stmts = (kind, o, e) => { const p = run(kind, o, e); assert.deepEqual(p.errors, [], p.errors.join('|')); return p.statements }

// ── new tables ──
const fresh = (autoType) => ({ name: 'users', indexes: [idx('ix_email', ['email'], { isNew: true, unique: true })], columns: [
  col('id', autoType, { isNew: true, primaryKey: true, nullable: false, autoIncrement: true }),
  col('email', 'varchar(100)', { isNew: true, nullable: false }),
  col('active', 'boolean', { isNew: true, nullable: false, defaultValue: 'true' })] })

assert.deepEqual(stmts('postgres', null, fresh('integer')), [
  'CREATE TABLE "app"."users" (\n  "id" integer GENERATED BY DEFAULT AS IDENTITY NOT NULL,\n  "email" varchar(100) NOT NULL,\n  "active" boolean NOT NULL DEFAULT true,\n  PRIMARY KEY ("id")\n)',
  'CREATE UNIQUE INDEX "ix_email" ON "app"."users" ("email")'])
assert.deepEqual(stmts('mysql', null, fresh('int')), [
  'CREATE TABLE `app`.`users` (\n  `id` int NOT NULL AUTO_INCREMENT,\n  `email` varchar(100) NOT NULL,\n  `active` boolean NOT NULL DEFAULT true,\n  PRIMARY KEY (`id`)\n)',
  'CREATE UNIQUE INDEX `ix_email` ON `app`.`users` (`email`)'])
assert.deepEqual(stmts('mssql', null, fresh('int')), [
  'CREATE TABLE [app].[dbo].[users] (\n  [id] int IDENTITY(1,1) NOT NULL,\n  [email] varchar(100) NOT NULL,\n  [active] boolean NOT NULL DEFAULT true,\n  CONSTRAINT [PK_users] PRIMARY KEY ([id])\n)',
  'CREATE UNIQUE INDEX [ix_email] ON [app].[dbo].[users] ([email])'])
assert.deepEqual(stmts('sqlite', null, fresh('integer')), [
  'CREATE TABLE "users" (\n  "id" INTEGER PRIMARY KEY AUTOINCREMENT,\n  "email" varchar(100) NOT NULL,\n  "active" boolean NOT NULL DEFAULT true\n)',
  'CREATE UNIQUE INDEX "ix_email" ON "users" ("email")'])
console.log('create table x4 OK')

// ── validation ──
const bad = (d, re, kind = 'postgres') => { const p = run(kind, null, d); assert.ok(p.errors.some((e) => re.test(e)), `${re}: ${p.errors}`); assert.deepEqual(p.statements, []) }
bad({ name: '', columns: [col('a', 'int', { isNew: true })], indexes: [] }, /needs a name/)
bad({ name: 't', columns: [], indexes: [] }, /at least one column/)
bad({ name: 't', columns: [col('a', 'int', { isNew: true }), col('A', 'int', { isNew: true })], indexes: [] }, /Duplicate column/)
bad({ name: 't', columns: [col('a', '', { isNew: true })], indexes: [] }, /needs a type/)
bad({ name: 't', columns: [col('a', 'int', { isNew: true })], indexes: [idx('i', ['zzz'], { isNew: true })] }, /unknown column "zzz"/)
bad({ name: 't', columns: [col('a', 'int', { isNew: true })], indexes: [idx('i', [], { isNew: true })] }, /at least one column/)
bad({ name: 't', columns: [col('a', 'int', { isNew: true, autoIncrement: true })], indexes: [] }, /primary key/, 'sqlite')
bad({ name: 't', columns: [col('a', 'int', { isNew: true, autoIncrement: true })], indexes: [] }, /must be a key/i.source ? /needs the auto-increment column/ : /x/, 'mysql')
console.log('validation OK')

// ── alter ──
const base = () => ({ name: 'users', pkName: 'users_pkey', indexes: [idx('ix_name', ['name']), idx('ix_expr', ['name'], { locked: true })], columns: [
  col('id', 'integer', { primaryKey: true, nullable: false }),
  col('name', 'text', { nullable: false, defaultValue: "'x'", defaultConstraint: 'DF_name' }),
  col('legacy', 'int')] })

const same = base()
for (const k of ['postgres', 'mysql', 'mssql', 'sqlite']) assert.deepEqual(stmts(k, base(), clone(same)), [], `${k}: no-op diff must be empty`)
console.log('no-op diff empty x4 OK')

// add + drop + modify + rename (postgres)
let e = base()
e.columns = e.columns.filter((c) => c.name !== 'legacy')                                  // drop
e.columns.push(col('age', 'integer', { isNew: true, defaultValue: '0', nullable: false })) // add
Object.assign(e.columns[1], { type: 'varchar(50)', nullable: true, defaultValue: null })   // modify
e.columns[1].name = 'full_name'; e.indexes[0].columns = ['full_name']                      // rename; index follows
let p = run('postgres', base(), e); assert.deepEqual(p.errors, [])
assert.deepEqual(p.statements, [
  'ALTER TABLE "app"."users" DROP COLUMN "legacy"',
  'ALTER TABLE "app"."users" RENAME COLUMN "name" TO "full_name"',
  'ALTER TABLE "app"."users" ALTER COLUMN "full_name" DROP DEFAULT',
  'ALTER TABLE "app"."users" ALTER COLUMN "full_name" TYPE varchar(50) USING "full_name"::varchar(50)',
  'ALTER TABLE "app"."users" ALTER COLUMN "full_name" DROP NOT NULL',
  'ALTER TABLE "app"."users" ADD COLUMN "age" integer NOT NULL DEFAULT 0'])
assert.ok(p.warnings.some((w) => /legacy.*deleted/.test(w)))
console.log('postgres alter OK (renamed column keeps its index, no index churn)')

// postgres: a default survives a type change (dropped first, restored after)
e = base(); e.columns[1].type = 'varchar(9)'
assert.deepEqual(stmts('postgres', base(), e), [
  'ALTER TABLE "app"."users" ALTER COLUMN "name" DROP DEFAULT',
  'ALTER TABLE "app"."users" ALTER COLUMN "name" TYPE varchar(9) USING "name"::varchar(9)',
  `ALTER TABLE "app"."users" ALTER COLUMN "name" SET DEFAULT 'x'`])
e = base(); e.columns[2].type = 'bigint'   // no default involved: just the TYPE change
assert.deepEqual(stmts('postgres', base(), e), ['ALTER TABLE "app"."users" ALTER COLUMN "legacy" TYPE bigint USING "legacy"::bigint'])
console.log('postgres default survives type change OK')

// mysql: CHANGE for rename, MODIFY for modify, extra preserved
e = base(); e.columns[2].extra = "COMMENT 'keep me'"; const mo = base(); mo.columns[2].extra = "COMMENT 'keep me'"
e = clone(mo); e.columns[2].type = 'bigint'
assert.deepEqual(stmts('mysql', mo, e), ["ALTER TABLE `app`.`users` MODIFY COLUMN `legacy` bigint NULL COMMENT 'keep me'"])
e = clone(mo); e.columns[2].name = 'old'
assert.deepEqual(stmts('mysql', mo, e), ["ALTER TABLE `app`.`users` CHANGE COLUMN `legacy` `old` int NULL COMMENT 'keep me'"])
console.log('mysql modify/rename keeps extra OK')

// mssql: default constraint dance, sp_rename, drop with default
e = base(); e.columns[1].type = 'nvarchar(10)'; e.columns[1].defaultValue = "'y'"
assert.deepEqual(stmts('mssql', base(), e), [
  'ALTER TABLE [app].[dbo].[users] DROP CONSTRAINT [DF_name]',
  'ALTER TABLE [app].[dbo].[users] ALTER COLUMN [name] nvarchar(10) NOT NULL',
  "ALTER TABLE [app].[dbo].[users] ADD DEFAULT 'y' FOR [name]"])
e = base(); e.columns[1].name = "na'me"; e.indexes[0].columns = ["na'me"]
assert.deepEqual(stmts('mssql', base(), e), ["EXEC sp_rename 'dbo.users.name', 'na''me', 'COLUMN'"])
e = base(); e.columns = e.columns.filter((c) => c.name !== 'name'); e.indexes = []
assert.deepEqual(stmts('mssql', base(), e).slice(0, 3), ['DROP INDEX [ix_name] ON [app].[dbo].[users]', 'ALTER TABLE [app].[dbo].[users] DROP CONSTRAINT [DF_name]', 'ALTER TABLE [app].[dbo].[users] DROP COLUMN [name]'])
e = base(); e.columns.push(col('c', 'int', { isNew: true }))
assert.deepEqual(stmts('mssql', base(), e), ['ALTER TABLE [app].[dbo].[users] ADD [c] int NULL'])
e = base(); e.columns[2].autoIncrement = true
assert.ok(run('mssql', base(), e).errors.some((x) => /IDENTITY/.test(x)))
console.log('mssql OK')

// indexes: change = drop+create after columns; locked index never touched; removal
e = base(); e.indexes[0].unique = true
assert.deepEqual(stmts('postgres', base(), e), ['DROP INDEX "app"."ix_name"', 'CREATE UNIQUE INDEX "ix_name" ON "app"."users" ("name")'])
e = base(); e.indexes = [e.indexes[1]]   // user removed ix_name, kept the locked one
assert.deepEqual(stmts('mysql', base(), e), ['DROP INDEX `ix_name` ON `app`.`users`'])
e = base(); e.indexes = []                // even if the locked row vanished from the list, it must not be dropped
assert.deepEqual(stmts('sqlite', base(), e), ['DROP INDEX "ix_name"'])
e = base(); e.indexes.push(idx('ix_new', ['id', 'legacy'], { isNew: true }))
assert.deepEqual(stmts('postgres', base(), e), ['CREATE INDEX "ix_new" ON "app"."users" ("id", "legacy")'])
console.log('indexes OK')

// primary key changes
e = base(); e.columns[1].primaryKey = true; e.columns[1].nullable = false
assert.deepEqual(stmts('postgres', base(), e).filter((s) => /PRIMARY|pkey/.test(s)), ['ALTER TABLE "app"."users" DROP CONSTRAINT "users_pkey"', 'ALTER TABLE "app"."users" ADD PRIMARY KEY ("id", "name")'])
assert.deepEqual(stmts('mysql', base(), e).filter((s) => /PRIMARY/.test(s)), ['ALTER TABLE `app`.`users` DROP PRIMARY KEY', 'ALTER TABLE `app`.`users` ADD PRIMARY KEY (`id`, `name`)'])
assert.ok(run('sqlite', base(), e).errors.some((x) => /primary key/.test(x)))
const noName = base(); delete noName.pkName
assert.ok(run('postgres', noName, e).errors.some((x) => /no known name/.test(x)))
console.log('primary key OK')

// sqlite limits + supported ops
e = base(); e.columns[1].type = 'varchar(5)'
assert.ok(run('sqlite', base(), e).errors.some((x) => /cannot change the type/.test(x)))
e = base(); e.columns[2].name = 'renamed'; e.columns.push(col('z', 'int', { isNew: true })); e.columns = e.columns.filter((c) => c.name !== 'name'); e.indexes = [e.indexes[1]]
assert.deepEqual(stmts('sqlite', base(), e), ['DROP INDEX "ix_name"', 'ALTER TABLE "users" DROP COLUMN "name"', 'ALTER TABLE "users" RENAME COLUMN "legacy" TO "renamed"', 'ALTER TABLE "users" ADD COLUMN "z" int'])
console.log('sqlite limits OK')

// locked column is never modified
e = base(); e.columns[2].locked = true; const lockedBase = base(); lockedBase.columns[2].locked = true
const le = clone(lockedBase); le.columns[2].type = 'text'
assert.deepEqual(stmts('postgres', lockedBase, le), [])
console.log('locked columns untouched OK')

// ── foreign keys ──
const fk = (name, columns, refTable, o = {}) => ({ id: name + (++n), originalName: o.isNew ? null : name, name, columns, refTable, refColumns: ['id'], onDelete: 'NO ACTION', onUpdate: 'NO ACTION', ...o })
const withFk = () => { const d = base(); d.foreignKeys = [fk('fk_owner', ['legacy'], 'owners')]; return d }

// create table with FKs, one per dialect (actions omitted when NO ACTION)
{
  const d = { name: 'orders', indexes: [], columns: [col('id', 'int', { isNew: true, primaryKey: true, nullable: false }), col('user_id', 'int', { isNew: true })],
    foreignKeys: [fk('fk_user', ['user_id'], 'users', { isNew: true, onDelete: 'CASCADE', onUpdate: 'SET NULL' }), fk('fk_x', ['user_id'], 'x', { isNew: true, refSchema: 'other' })] }
  assert.match(stmts('postgres', null, d)[0], /,\n  CONSTRAINT "fk_user" FOREIGN KEY \("user_id"\) REFERENCES "app"\."users" \("id"\) ON DELETE CASCADE ON UPDATE SET NULL,\n  CONSTRAINT "fk_x" FOREIGN KEY \("user_id"\) REFERENCES "other"\."x" \("id"\)\n\)$/)
  assert.match(stmts('mysql', null, d)[0], /REFERENCES `app`\.`users` \(`id`\) ON DELETE CASCADE ON UPDATE SET NULL/)
  assert.match(stmts('mssql', null, d)[0], /REFERENCES \[dbo\]\.\[users\] \(\[id\]\) ON DELETE CASCADE ON UPDATE SET NULL/)
  assert.match(stmts('mssql', null, d)[0], /REFERENCES \[other\]\.\[x\]/)
  assert.match(stmts('sqlite', null, d)[0], /CONSTRAINT "fk_user" FOREIGN KEY \("user_id"\) REFERENCES "users" \("id"\) ON DELETE CASCADE/)
}

// untouched FKs are a no-op everywhere; a renamed column keeps its FK
for (const k of ['postgres', 'mysql', 'mssql', 'sqlite']) assert.deepEqual(stmts(k, withFk(), clone(withFk())), [], `${k}: FK no-op`)
e = withFk(); e.columns[2].name = 'renamed'; e.foreignKeys[0].columns = ['renamed']
assert.deepEqual(stmts('postgres', withFk(), e), ['ALTER TABLE "app"."users" RENAME COLUMN "legacy" TO "renamed"'])

// add / drop / change on an existing table, per dialect (FK dropped before indexes, added last)
e = withFk(); e.foreignKeys.push(fk('fk_new', ['id'], 'parents', { isNew: true, onDelete: 'CASCADE' }))
assert.deepEqual(stmts('postgres', withFk(), e), ['ALTER TABLE "app"."users" ADD CONSTRAINT "fk_new" FOREIGN KEY ("id") REFERENCES "app"."parents" ("id") ON DELETE CASCADE'])
assert.deepEqual(stmts('mysql', withFk(), e), ['ALTER TABLE `app`.`users` ADD CONSTRAINT `fk_new` FOREIGN KEY (`id`) REFERENCES `app`.`parents` (`id`) ON DELETE CASCADE'])
assert.deepEqual(stmts('mssql', withFk(), e), ['ALTER TABLE [app].[dbo].[users] ADD CONSTRAINT [fk_new] FOREIGN KEY ([id]) REFERENCES [dbo].[parents] ([id]) ON DELETE CASCADE'])
e = withFk(); e.foreignKeys = []
assert.deepEqual(stmts('postgres', withFk(), e), ['ALTER TABLE "app"."users" DROP CONSTRAINT "fk_owner"'])
assert.deepEqual(stmts('mysql', withFk(), e), ['ALTER TABLE `app`.`users` DROP FOREIGN KEY `fk_owner`'])
assert.deepEqual(stmts('mssql', withFk(), e), ['ALTER TABLE [app].[dbo].[users] DROP CONSTRAINT [fk_owner]'])
e = withFk(); e.foreignKeys[0].onDelete = 'CASCADE'
assert.deepEqual(stmts('postgres', withFk(), e), ['ALTER TABLE "app"."users" DROP CONSTRAINT "fk_owner"', 'ALTER TABLE "app"."users" ADD CONSTRAINT "fk_owner" FOREIGN KEY ("legacy") REFERENCES "app"."owners" ("id") ON DELETE CASCADE'])

// ordering: FK drop first, then dropping its index and column; FK add after the new index
e = withFk(); e.foreignKeys = []; e.columns = e.columns.filter((c) => c.name !== 'legacy')
assert.deepEqual(stmts('mysql', withFk(), e), ['ALTER TABLE `app`.`users` DROP FOREIGN KEY `fk_owner`', 'ALTER TABLE `app`.`users` DROP COLUMN `legacy`'])
e = withFk(); e.indexes.push(idx('ix_o', ['legacy'], { isNew: true })); e.foreignKeys[0].refTable = 'owners2'
const ord = stmts('mysql', withFk(), e)
assert.ok(ord.findIndex((x) => /DROP FOREIGN KEY/.test(x)) < ord.findIndex((x) => /CREATE INDEX/.test(x)) && ord.findIndex((x) => /CREATE INDEX/.test(x)) < ord.findIndex((x) => /ADD CONSTRAINT/.test(x)), 'drop FK < create index < add FK')

// SQLite cannot touch FKs of an existing table; locked FKs are never touched
e = withFk(); e.foreignKeys = []
assert.ok(run('sqlite', withFk(), e).errors.some((x) => /cannot add or drop foreign keys/.test(x)))
const lockedFkBase = withFk(); lockedFkBase.foreignKeys[0].locked = true
e = clone(lockedFkBase); e.foreignKeys = []
assert.deepEqual(stmts('postgres', lockedFkBase, e), [])

// validation
const badFk = (mut, re, kind = 'postgres') => { const d = withFk(); mut(d.foreignKeys[0]); const p = run(kind, d, d); assert.ok(p.errors.some((x) => re.test(x)), `${re}: ${p.errors}`) }
badFk((f) => (f.name = ''), /foreign key needs a name/)
badFk((f) => (f.columns = []), /needs at least one column/)
badFk((f) => (f.columns = ['nope']), /unknown column "nope"/)
badFk((f) => (f.refTable = ''), /needs a referenced table/)
badFk((f) => (f.refColumns = []), /needs referenced columns/)
badFk((f) => (f.refColumns = ['a', 'b']), /as many referenced columns/)
badFk((f) => (f.onDelete = 'RESTRICT'), /no RESTRICT/, 'mssql')
badFk((f) => (f.onUpdate = 'SET DEFAULT'), /does not support SET DEFAULT/, 'mysql')
console.log('foreign keys OK')

// NOT NULL add without default warns
e = base(); e.columns.push(col('req', 'int', { isNew: true, nullable: false }))
assert.ok(run('postgres', base(), e).warnings.some((w) => /no default/.test(w)))
assert.equal(formatDdl(['A', 'B']), 'A;\n\nB;')
console.log('ALL DDL TESTS PASSED')
