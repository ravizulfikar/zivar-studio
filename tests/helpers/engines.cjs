// Shared test fixtures: real SQLite / PostgreSQL / MySQL containers (a "container" is a SQLite file,
// a PostgreSQL schema or a MySQL database) plus the same logical dataset seeded into any of them.
const fs = require('node:fs')
const os = require('node:os')
const path = require('node:path')
const { startPg, startMysql } = require('./servers.cjs')
const { SqliteDriver } = require('../.build/sqlite.cjs')
const { PostgresDriver } = require('../.build/postgres.cjs')
const { MySqlDriver } = require('../.build/mysql.cjs')

const TRICKY = ['plain', 'back\\slash \\n literal', '; DROP TABLE items; --', 'it\'s "quoted"', 'emoji 😀 ünï 日本語', 'line1\nline2\r\nline3\ttab', '', null]
const BULK = 2300 // more than one 2000-row transfer page

class Env {
  constructor() {
    this.pg = null
    this.my = null
    this.dir = fs.mkdtempSync(path.join(os.tmpdir(), 'zivar-env-'))
    this.opened = []
    this.counter = 0
  }

  async init(kinds = ['sqlite', 'postgres', 'mysql']) {
    if (kinds.includes('postgres')) this.pg = await startPg()
    if (kinds.includes('mysql')) this.my = await startMysql()
    this.kinds = ['sqlite', ...(this.pg ? ['postgres'] : []), ...(this.my ? ['mysql'] : [])]
    return this
  }

  /** A fresh empty container of the given engine, with its own connection. */
  async container(kind, label = 'c') {
    const name = `${label}${++this.counter}`
    let driver
    let container
    if (kind === 'sqlite') {
      driver = new SqliteDriver({ id: name, name, kind, database: path.join(this.dir, `${name}.db`) })
      container = 'main'
      await driver.connect()
    } else if (kind === 'postgres') {
      driver = new PostgresDriver({ id: name, name, kind, ...this.pg.target })
      container = name
      await driver.connect()
      await driver.query(`CREATE SCHEMA ${container}`, null)
    } else {
      driver = new MySqlDriver({ id: name, name, kind, ...this.my.target })
      container = name
      await driver.connect()
      await driver.query(`CREATE DATABASE \`${container}\``, null)
    }
    const c = { kind, driver, container, name }
    this.opened.push(c)
    return c
  }

  async stop() {
    for (const c of this.opened) await c.driver.close().catch(() => undefined)
    this.pg?.stop()
    this.my?.stop()
    fs.rmSync(this.dir, { recursive: true, force: true }) // the SQLite files of this run
  }
}

/** parents(id, label) and items(id auto, parent_id -> parents, title unique per parent, …) with tricky data. */
async function seed(c) {
  const { kind, driver, container } = c
  const q = (sql) => driver.query(sql, container === 'main' ? null : null)
  const t = (name) => (kind === 'sqlite' ? `"${name}"` : kind === 'mysql' ? `\`${container}\`.\`${name}\`` : `"${container}"."${name}"`)
  const itemCols = ['parent_id', 'title', 'qty', 'price', 'note', 'bin', 'created', 'big', 'meta']

  if (kind === 'sqlite') {
    await q('CREATE TABLE parents (id INTEGER PRIMARY KEY, label TEXT NOT NULL)')
    await q('CREATE TABLE items (id INTEGER PRIMARY KEY AUTOINCREMENT, parent_id INTEGER REFERENCES parents(id) ON DELETE CASCADE, title TEXT NOT NULL, qty INTEGER DEFAULT 1, price REAL, note TEXT, bin BLOB, created TEXT, big TEXT, meta TEXT)')
    await q('CREATE INDEX ix_title ON items (title)')
    await q('CREATE UNIQUE INDEX ux_pt ON items (parent_id, title)')
  } else if (kind === 'postgres') {
    await q(`CREATE TABLE ${t('parents')} (id integer PRIMARY KEY, label text NOT NULL)`)
    await q(`CREATE TABLE ${t('items')} (id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, parent_id integer REFERENCES ${t('parents')}(id) ON DELETE CASCADE, title text NOT NULL, qty integer DEFAULT 1, price numeric(10,2), note text, bin bytea, created timestamp, big bigint, meta jsonb)`)
    await q(`CREATE INDEX ix_title ON ${t('items')} (title)`)
    await q(`CREATE UNIQUE INDEX ux_pt ON ${t('items')} (parent_id, title)`)
  } else {
    await q(`CREATE TABLE ${t('parents')} (id INT PRIMARY KEY, label VARCHAR(50) NOT NULL) ENGINE=InnoDB`)
    await q(
      `CREATE TABLE ${t('items')} (id INT AUTO_INCREMENT PRIMARY KEY, parent_id INT, title VARCHAR(100) NOT NULL, qty INT DEFAULT 1, price DECIMAL(10,2), note TEXT, bin BLOB, created DATETIME, big BIGINT, meta JSON,
         KEY ix_title (title), UNIQUE KEY ux_pt (parent_id, title), CONSTRAINT fk_items_parent FOREIGN KEY (parent_id) REFERENCES parents(id) ON DELETE CASCADE) ENGINE=InnoDB`
    )
  }

  await driver.insertRows(container, { name: 'parents', type: 'table', schema: kind === 'postgres' ? container : undefined }, ['id', 'label'], [[1, 'Alpha'], [2, "O'Brien & Sons"]])
  // JSON is not only objects: bare strings, numbers, booleans and arrays are valid values too, and drivers hand them over parsed.
  const JSONS = ['{"a":1,"b":[1,2,{"c":null}],"s":"ünï \\"q\\" 😀"}', '[1,"two",null,{"k":true}]', '"just a string"', '42', 'true', null]
  const rows = TRICKY.map((s, i) => [(i % 2) + 1, `${s ?? 'NULL'}#${i}`, i === 1 ? null : i, i === 2 ? null : `${i}.25`, s, i === 0 ? Buffer.from([0, 1, 2, 255]) : null, '2025-09-17 13:39:18', '9007199254740993', JSONS[i % JSONS.length]])
  for (let i = 0; i < BULK; i++) rows.push([1, `bulk ${i}`, i, '0.50', `note ${i}`, null, null, null, i % 100 === 0 ? JSONS[(i / 100) % JSONS.length] : null])
  await driver.insertRows(container, { name: 'items', type: 'table', schema: kind === 'postgres' ? container : undefined }, itemCols, rows)
  return { parents: 2, items: rows.length }
}

/** JSON compared by meaning: a text column holding '{"a":1}' and a jsonb column holding {a:1} are the same value. */
function canonJson(v) {
  let x = v
  if (typeof x === 'string') {
    try {
      x = JSON.parse(x)
    } catch {
      /* a bare string value such as: just a string */
    }
  }
  const sort = (y) => (Array.isArray(y) ? y.map(sort) : y && typeof y === 'object' ? Object.fromEntries(Object.keys(y).sort().map((k) => [k, sort(y[k])])) : y)
  return JSON.stringify(sort(x))
}

const hex = (v) => (v instanceof Uint8Array ? Buffer.from(v).toString('hex') : v)

/** Rows of a table in a comparable form that survives a trip through another engine. */
async function snapshot(c, name, columns) {
  const obj = { name, type: 'table', schema: c.kind === 'postgres' ? c.container : undefined }
  const p = await c.driver.tableData(c.container, obj, { limit: 100000, offset: 0, orderBy: { column: 'id', dir: 'asc' } })
  const idx = columns.map((col) => p.columns.indexOf(col))
  return p.rows.map((r) =>
    idx.map((i, k) => {
      const v = hex(r[i])
      const col = columns[k]
      if (v === null || v === undefined) return null
      if (col === 'price') return Number(v)
      if (col === 'created') return String(v).slice(0, 19)
      if (col === 'big' || col === 'qty' || col === 'id' || col === 'parent_id') return String(v)
      if (col === 'meta') return canonJson(v)
      return v
    })
  )
}

module.exports = { Env, seed, snapshot, TRICKY, BULK }
