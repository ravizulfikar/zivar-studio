// Structure synchronisation on real databases: make a target database's structure match a source's.
const assert = require('node:assert/strict')
const { Env } = require('./helpers/engines.cjs')
const { planSyncTable, planNewTable, orderByDependencies } = require('./.build/sync.cjs')
const { dropTableDdl } = require('./.build/ddl.cjs')

const tbl = (c, name) => (c.kind === 'sqlite' ? `"${name}"` : c.kind === 'mysql' ? `\`${c.container}\`.\`${name}\`` : `"${c.container}"."${name}"`)
const obj = (c, name) => ({ name, type: 'table', schema: c.kind === 'postgres' ? c.container : undefined })
const ctxOf = (c) => ({ kind: c.kind, container: c.container })

// Source and target differ in the ways a real migration does. SQLite cannot change a column's type, so
// there the source and target agree on types and differ in added columns, indexes and a new table.
async function build(src, dst) {
  const run = (c, sql) => c.driver.query(sql, null)
  const lite = src.kind === 'sqlite'
  const id = { sqlite: 'INTEGER PRIMARY KEY AUTOINCREMENT', postgres: 'integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', mysql: 'INT AUTO_INCREMENT PRIMARY KEY' }[src.kind]
  const text = lite ? 'TEXT' : src.kind === 'mysql' ? 'VARCHAR(200)' : 'varchar(200)'
  const oldText = lite ? 'TEXT' : src.kind === 'mysql' ? 'VARCHAR(50)' : 'text'
  const idInt = src.kind === 'mysql' ? 'INT' : 'INTEGER'
  const engine = src.kind === 'mysql' ? ' ENGINE=InnoDB' : ''
  const num = lite ? 'REAL' : 'DECIMAL(10,2)'

  for (const c of [src, dst]) await run(c, `CREATE TABLE ${tbl(c, 'parents')} (id ${idInt} PRIMARY KEY, label ${oldText} NOT NULL)${engine}`)

  await run(src, `CREATE TABLE ${tbl(src, 'users')} (id ${id}, email ${text} NOT NULL, age ${idInt} NOT NULL DEFAULT 0, nick ${oldText})${engine}`)
  await run(src, `CREATE UNIQUE INDEX ux_email ON ${tbl(src, 'users')} (email)`)
  await run(src, `CREATE INDEX ix_age ON ${tbl(src, 'users')} (age)`)

  await run(dst, `CREATE TABLE ${tbl(dst, 'users')} (id ${id}, email ${oldText} NOT NULL, legacy ${idInt}, nick ${oldText})${engine}`)
  await run(dst, `CREATE INDEX ix_email ON ${tbl(dst, 'users')} (email)`)
  await run(dst, `INSERT INTO ${tbl(dst, 'users')} (email, legacy) VALUES ('a@x', 1), ('b@x', 2)`)

  // only in the source (with a foreign key into users) and only in the target
  const fk = lite ? `, FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE` : `, CONSTRAINT fk_orders_user FOREIGN KEY (user_id) REFERENCES ${tbl(src, 'users')}(id) ON DELETE CASCADE`
  await run(src, `CREATE TABLE ${tbl(src, 'orders')} (id ${idInt} PRIMARY KEY, user_id ${idInt}, total ${num}${fk})${engine}`)
  await run(dst, `CREATE TABLE ${tbl(dst, 'extra_table')} (id ${idInt} PRIMARY KEY)${engine}`)
}

async function designs(c) {
  const out = new Map()
  for (const o of (await c.driver.objects(c.container)).filter((x) => x.type === 'table')) out.set(o.name, await c.driver.designInfo(c.container, o))
  return out
}

;(async () => {
  const env = await new Env().init()
  try {
    for (const kind of env.kinds) {
      const src = await env.container(kind, 's')
      const dst = await env.container(kind, 'd')
      await build(src, dst)
      const ctx = ctxOf(dst)
      const opts = { dropExtras: false, sourceContainer: src.container }
      const S = await designs(src)
      const T = await designs(dst)

      // ── plan ──
      const same = planSyncTable(ctx, T.get('parents'), S.get('parents'), opts)
      assert.deepEqual(same.statements, [], `${kind}: an identical table needs no DDL`)
      const users = planSyncTable(ctx, T.get('users'), S.get('users'), opts)
      assert.deepEqual(users.errors, [], `${kind}: ${users.errors.join('|')}`)
      assert.ok(users.statements.some((s) => /age/.test(s) && /ADD/.test(s)), `${kind}: new column`)
      assert.ok(!users.statements.some((s) => /legacy/.test(s)), `${kind}: target-only column is kept by default`)
      if (kind !== 'sqlite') assert.ok(users.statements.some((s) => /email/i.test(s) && /(TYPE|MODIFY)/i.test(s)), `${kind}: column type change`)
      const orders = planNewTable(ctx, S.get('orders'), { sourceContainer: src.container })
      assert.deepEqual(orders.errors, [])
      assert.equal(orders.foreignKeys.length, kind === 'sqlite' ? 0 : 1, `${kind}: FKs deferred except in SQLite`)

      // ── apply (the target's users table already holds rows) ──
      await dst.driver.executeDdl(dst.container, users.statements)
      await dst.driver.executeDdl(dst.container, orders.statements)
      if (orders.foreignKeys.length) await dst.driver.executeDdl(dst.container, orders.foreignKeys)
      assert.equal(Number((await dst.driver.query(`SELECT count(*) FROM ${tbl(dst, 'users')}`, null)).rows[0][0]), 2, `${kind}: existing rows survive the sync`)
      assert.deepEqual((await dst.driver.query(`SELECT age FROM ${tbl(dst, 'users')} ORDER BY id`, null)).rows, [[0], [0]], `${kind}: the new NOT NULL column took its default for old rows`)

      // ── converged: re-planning every shared table gives nothing; the new table equals the source's ──
      const T2 = await designs(dst)
      for (const name of ['parents', 'users']) {
        const again = planSyncTable(ctx, T2.get(name), S.get(name), opts)
        assert.deepEqual(again.statements.concat(again.errors), [], `${kind}: ${name} still differs after sync: ${JSON.stringify(again.statements)}`)
      }
      const newOrders = planSyncTable(ctx, T2.get('orders'), S.get('orders'), opts)
      assert.deepEqual(newOrders.statements.concat(newOrders.errors), [], `${kind}: the created table differs from the source`)
      if (kind !== 'sqlite') assert.equal(T2.get('orders').foreignKeys.length, 1)
      console.log(`  [${kind}] plan, apply on populated table, new table with FK, convergence OK`)

      // ── dropExtras removes what only the target has ──
      const strict = planSyncTable(ctx, T2.get('users'), S.get('users'), { ...opts, dropExtras: true })
      assert.ok(strict.statements.some((s) => /DROP COLUMN/.test(s) && /legacy/.test(s)), `${kind}: dropExtras drops the extra column`)
      assert.ok(strict.warnings.some((w) => /legacy.*deleted/.test(w)))
      await dst.driver.executeDdl(dst.container, strict.statements)
      const T3 = await designs(dst)
      // ADD COLUMN appends, so the order of columns is not synchronised — only which columns exist.
      assert.deepEqual(T3.get('users').columns.map((c) => c.name).sort(), S.get('users').columns.map((c) => c.name).sort(), `${kind}: columns now match the source`)
      assert.deepEqual(planSyncTable(ctx, T3.get('users'), S.get('users'), { ...opts, dropExtras: true }).statements, [])

      // ── tables only in the target can be dropped, children first ──
      await dst.driver.executeDdl(dst.container, [dropTableDdl(ctx, 'extra_table')])
      assert.ok(!(await dst.driver.objects(dst.container)).some((o) => o.name === 'extra_table'))
      const order = orderByDependencies([...T3.values()].map((d) => ({ name: d.name, d })), (t) => (t.d.foreignKeys ?? []).map((f) => f.refTable)).ordered.map((t) => t.name)
      assert.ok(order.indexOf('users') < order.indexOf('orders') || kind === 'sqlite', `${kind}: users sorts before orders`)
      console.log(`  [${kind}] dropExtras, dropping target-only tables OK`)
    }
    console.log('ALL SYNC TESTS PASSED')
  } finally {
    await env.stop()
  }
})().catch((e) => {
  console.error('FAIL', e)
  process.exit(1)
})
