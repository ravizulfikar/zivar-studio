import type { DbKind } from '@shared/types'

export interface BuiltinSnippet {
  name: string
  body: (kind: DbKind) => string
}

const CREATE_TABLE: Record<DbKind, string> = {
  postgres: 'CREATE TABLE table_name (\n  id integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,\n  name text NOT NULL,\n  created_at timestamp DEFAULT now()\n);',
  mysql: 'CREATE TABLE table_name (\n  id INT AUTO_INCREMENT PRIMARY KEY,\n  name VARCHAR(255) NOT NULL,\n  created_at DATETIME DEFAULT CURRENT_TIMESTAMP\n);',
  mssql: 'CREATE TABLE table_name (\n  id INT IDENTITY(1,1) PRIMARY KEY,\n  name NVARCHAR(255) NOT NULL,\n  created_at DATETIME2 DEFAULT SYSUTCDATETIME()\n);',
  sqlite: 'CREATE TABLE table_name (\n  id INTEGER PRIMARY KEY AUTOINCREMENT,\n  name TEXT NOT NULL,\n  created_at TEXT DEFAULT CURRENT_TIMESTAMP\n);'
}

export const BUILTIN_SNIPPETS: BuiltinSnippet[] = [
  { name: 'SELECT', body: () => 'SELECT *\nFROM table_name\nWHERE condition;' },
  { name: 'SELECT … JOIN', body: () => 'SELECT a.*, b.*\nFROM table_a AS a\nJOIN table_b AS b ON b.a_id = a.id\nWHERE condition;' },
  { name: 'INSERT', body: () => 'INSERT INTO table_name (column1, column2)\nVALUES (value1, value2);' },
  { name: 'UPDATE', body: () => 'UPDATE table_name\nSET column1 = value1\nWHERE condition;' },
  { name: 'DELETE', body: () => 'DELETE FROM table_name\nWHERE condition;' },
  { name: 'CREATE TABLE', body: (k) => CREATE_TABLE[k] },
  { name: 'WITH (CTE)', body: () => 'WITH cte AS (\n  SELECT *\n  FROM table_name\n  WHERE condition\n)\nSELECT * FROM cte;' },
  { name: 'CASE', body: () => 'CASE\n  WHEN condition THEN result\n  ELSE other_result\nEND' },
  { name: 'EXISTS subquery', body: () => 'SELECT *\nFROM table_a AS a\nWHERE EXISTS (\n  SELECT 1 FROM table_b AS b WHERE b.a_id = a.id\n);' },
  { name: 'Window: ROW_NUMBER', body: () => 'SELECT *,\n  ROW_NUMBER() OVER (PARTITION BY column1 ORDER BY column2) AS rn\nFROM table_name;' },
  { name: 'Pagination', body: (k) => (k === 'mssql' ? 'ORDER BY id\nOFFSET 0 ROWS FETCH NEXT 50 ROWS ONLY;' : 'ORDER BY id\nLIMIT 50 OFFSET 0;') }
]
