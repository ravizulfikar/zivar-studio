import type { DbKind, DdlPlan, DesignColumn, DesignForeignKey, DesignIndex, FkAction, TableDesign } from './types'

/**
 * Turns the difference between a table as loaded (`original`, null for a new
 * table) and as edited into DDL statements. Pure and engine-aware, so the UI can
 * preview it live and the tests can run without a database.
 */

export interface DdlContext {
  kind: DbKind
  /** Database (MySQL, SQL Server) or schema (PostgreSQL); ignored for SQLite. */
  container: string
  /** SQL Server schema inside the database. */
  schema?: string
  /** Leave the database/schema prefix off table names, so the SQL can be run into any database (dumps). */
  unqualified?: boolean
}

type Quote = (id: string) => string

const quoter = (kind: DbKind): Quote =>
  kind === 'mysql'
    ? (s) => '`' + s.replace(/`/g, '``') + '`'
    : kind === 'mssql'
      ? (s) => '[' + s.replace(/]/g, ']]') + ']'
      : (s) => '"' + s.replace(/"/g, '""') + '"'

const lit = (s: string): string => `'${s.replace(/'/g, "''")}'`

function tableRef(ctx: DdlContext, name: string): string {
  const q = quoter(ctx.kind)
  switch (ctx.kind) {
    case 'sqlite':
      return q(name)
    case 'mssql':
      return ctx.unqualified ? `${q(ctx.schema ?? 'dbo')}.${q(name)}` : `${q(ctx.container)}.${q(ctx.schema ?? 'dbo')}.${q(name)}`
    default:
      return ctx.unqualified ? q(name) : `${q(ctx.container)}.${q(name)}`
  }
}

const norm = (s: string | null | undefined): string => (s ?? '').trim()
const hasDefault = (c: DesignColumn): boolean => norm(c.defaultValue) !== ''

/** One column as it appears in CREATE TABLE / ADD COLUMN / MySQL MODIFY. */
function columnDef(kind: DbKind, c: DesignColumn): string {
  const q = quoter(kind)
  const type = c.type.trim()
  if (c.generated) {
    const expr = `(${c.generated.expr.trim()})`
    const storage = c.generated.stored ? 'STORED' : 'VIRTUAL'
    if (kind === 'mssql') return `${q(c.name)} AS ${expr}${c.generated.stored ? ' PERSISTED' : ''}`
    return `${q(c.name)} ${type} GENERATED ALWAYS AS ${expr} ${storage}${kind !== 'sqlite' && !c.nullable ? ' NOT NULL' : ''}`
  }
  const dflt = hasDefault(c) ? ` DEFAULT ${norm(c.defaultValue)}` : ''
  switch (kind) {
    case 'postgres':
      return `${q(c.name)} ${type}${c.autoIncrement ? ' GENERATED BY DEFAULT AS IDENTITY' : ''}${c.nullable ? '' : ' NOT NULL'}${c.autoIncrement ? '' : dflt}`
    case 'mysql': {
      const coll = c.collation ? ` CHARACTER SET ${c.collation.split('_')[0]} COLLATE ${c.collation}` : ''
      return `${q(c.name)} ${type}${coll} ${c.nullable ? 'NULL' : 'NOT NULL'}${dflt}${c.autoIncrement ? ' AUTO_INCREMENT' : ''}${c.extra ? ` ${c.extra}` : ''}`
    }
    case 'mssql':
      return `${q(c.name)} ${type}${c.autoIncrement ? ' IDENTITY(1,1)' : ''} ${c.nullable ? 'NULL' : 'NOT NULL'}${dflt}`
    case 'sqlite':
      return `${q(c.name)} ${type}${c.nullable ? '' : ' NOT NULL'}${dflt}`
  }
}

const sameType = (a: string, b: string): boolean => norm(a).toLowerCase().replace(/\s+/g, ' ') === norm(b).toLowerCase().replace(/\s+/g, ' ')

function columnChanged(o: DesignColumn, e: DesignColumn): boolean {
  return (
    !sameType(o.type, e.type) ||
    o.nullable !== e.nullable ||
    norm(o.defaultValue) !== norm(e.defaultValue) ||
    o.autoIncrement !== e.autoIncrement ||
    norm(o.extra) !== norm(e.extra) ||
    norm(o.collation) !== norm(e.collation)
  )
}

const pkOf = (cols: DesignColumn[]): DesignColumn[] => cols.filter((c) => c.primaryKey)

function indexDdl(ctx: DdlContext, table: string, ix: DesignIndex): string {
  const q = quoter(ctx.kind)
  return `CREATE ${ix.unique ? 'UNIQUE ' : ''}INDEX ${q(ix.name)} ON ${table} (${ix.columns.map(q).join(', ')})`
}

function dropIndexDdl(ctx: DdlContext, table: string, name: string): string {
  const q = quoter(ctx.kind)
  switch (ctx.kind) {
    case 'postgres':
      return ctx.unqualified ? `DROP INDEX ${q(name)}` : `DROP INDEX ${q(ctx.container)}.${q(name)}`
    case 'sqlite':
      return `DROP INDEX ${q(name)}`
    default:
      return `DROP INDEX ${q(name)} ON ${table}`
  }
}

const fksOf = (d: TableDesign): DesignForeignKey[] => d.foreignKeys ?? []
const action = (a: FkAction | undefined): FkAction => a ?? 'NO ACTION'

/** Schema/database the FK points into: explicit, else the same place as the table itself. */
function refScope(ctx: DdlContext, fk: DesignForeignKey): string {
  return fk.refSchema?.trim() || (ctx.kind === 'mssql' ? (ctx.schema ?? 'dbo') : ctx.container)
}

function refTarget(ctx: DdlContext, fk: DesignForeignKey): string {
  const q = quoter(ctx.kind)
  if (ctx.kind === 'sqlite') return q(fk.refTable)
  // Without qualification, a reference into this table's own database/schema is just the table name.
  if (ctx.unqualified && ctx.kind !== 'mssql' && refScope(ctx, fk) === ctx.container) return q(fk.refTable)
  return `${q(refScope(ctx, fk))}.${q(fk.refTable)}`
}

function fkClause(ctx: DdlContext, fk: DesignForeignKey): string {
  const q = quoter(ctx.kind)
  const on = (kw: string, a: FkAction | undefined): string => (action(a) === 'NO ACTION' ? '' : ` ON ${kw} ${action(a)}`)
  return (
    `CONSTRAINT ${q(fk.name)} FOREIGN KEY (${fk.columns.map(q).join(', ')}) ` +
    `REFERENCES ${refTarget(ctx, fk)} (${fk.refColumns.map(q).join(', ')})${on('DELETE', fk.onDelete)}${on('UPDATE', fk.onUpdate)}`
  )
}

function dropFkDdl(ctx: DdlContext, table: string, name: string): string {
  const q = quoter(ctx.kind)
  return ctx.kind === 'mysql' ? `ALTER TABLE ${table} DROP FOREIGN KEY ${q(name)}` : `ALTER TABLE ${table} DROP CONSTRAINT ${q(name)}`
}

/** Problems that make a design impossible to apply, whatever the engine. */
function validate(ctx: DdlContext, d: TableDesign, isNew: boolean): string[] {
  const errors: string[] = []
  if (isNew && !norm(d.name)) errors.push('The table needs a name.')
  if (d.columns.length === 0) errors.push('A table needs at least one column.')

  const seen = new Set<string>()
  for (const c of d.columns) {
    const n = norm(c.name)
    if (!n) errors.push('Every column needs a name.')
    else if (seen.has(n.toLowerCase())) errors.push(`Duplicate column name: ${n}.`)
    seen.add(n.toLowerCase())
    if (n && !norm(c.type)) errors.push(`Column "${n}" needs a type.`)
  }

  const autos = d.columns.filter((c) => c.autoIncrement)
  if (autos.length > 1 && ctx.kind !== 'postgres') errors.push('Only one auto-increment column is allowed.')
  if (ctx.kind === 'sqlite' && autos.length === 1) {
    const pk = pkOf(d.columns)
    if (pk.length !== 1 || pk[0] !== autos[0]) errors.push('SQLite auto-increment requires that column to be the only primary key.')
  }
  if (ctx.kind === 'mysql' && autos.length === 1) {
    const a = autos[0]
    const keyed = a.primaryKey || d.indexes.some((ix) => ix.columns[0] === a.name)
    if (!keyed) errors.push(`MySQL needs the auto-increment column "${a.name}" to be a key (primary key or first column of an index).`)
  }

  const names = new Set<string>()
  for (const ix of d.indexes) {
    // Locked indexes are shown but never rewritten, so their definition is not ours to validate.
    if (ix.locked) continue
    const n = norm(ix.name)
    if (!n) errors.push('Every index needs a name.')
    else if (names.has(n.toLowerCase())) errors.push(`Duplicate index name: ${n}.`)
    names.add(n.toLowerCase())
    if (ix.columns.length === 0) errors.push(`Index "${n || '?'}" needs at least one column.`)
    for (const col of ix.columns) {
      if (!seen.has(col.toLowerCase())) errors.push(`Index "${n || '?'}" refers to unknown column "${col}".`)
    }
  }

  const fkNames = new Set<string>()
  for (const fk of fksOf(d)) {
    if (fk.locked) continue
    const n = norm(fk.name)
    const label = n || '?'
    if (!n) errors.push('Every foreign key needs a name.')
    else if (fkNames.has(n.toLowerCase())) errors.push(`Duplicate foreign key name: ${n}.`)
    fkNames.add(n.toLowerCase())
    if (fk.columns.length === 0) errors.push(`Foreign key "${label}" needs at least one column.`)
    for (const col of fk.columns) {
      if (!seen.has(col.toLowerCase())) errors.push(`Foreign key "${label}" refers to unknown column "${col}".`)
    }
    if (!norm(fk.refTable)) errors.push(`Foreign key "${label}" needs a referenced table.`)
    if (fk.refColumns.length === 0) errors.push(`Foreign key "${label}" needs referenced columns.`)
    else if (fk.refColumns.length !== fk.columns.length) errors.push(`Foreign key "${label}" must list as many referenced columns as columns (${fk.columns.length}).`)
    for (const a of [fk.onDelete, fk.onUpdate]) {
      if (ctx.kind === 'mssql' && a === 'RESTRICT') errors.push(`Foreign key "${label}": SQL Server has no RESTRICT; use NO ACTION.`)
      if (ctx.kind === 'mysql' && a === 'SET DEFAULT') errors.push(`Foreign key "${label}": MySQL (InnoDB) does not support SET DEFAULT.`)
    }
  }
  return errors
}

function createTable(ctx: DdlContext, d: TableDesign): string[] {
  const q = quoter(ctx.kind)
  const ref = tableRef(ctx, d.name)
  const pk = pkOf(d.columns)

  // SQLite spells auto-increment as part of an inline INTEGER PRIMARY KEY.
  const inlineSqlitePk = ctx.kind === 'sqlite' && pk.length === 1 && pk[0].autoIncrement ? pk[0] : null

  const defs = d.columns.map((c) =>
    c === inlineSqlitePk ? `${q(c.name)} INTEGER PRIMARY KEY AUTOINCREMENT` : columnDef(ctx.kind, c)
  )
  if (pk.length && !inlineSqlitePk) {
    const cols = pk.map((c) => q(c.name)).join(', ')
    defs.push(ctx.kind === 'mssql' ? `CONSTRAINT ${q(`PK_${d.name}`)} PRIMARY KEY (${cols})` : `PRIMARY KEY (${cols})`)
  }
  for (const fk of fksOf(d)) defs.push(fkClause(ctx, fk))
  const out = [`CREATE TABLE ${ref} (\n  ${defs.join(',\n  ')}\n)`]
  for (const ix of d.indexes) out.push(indexDdl(ctx, ref, ix))
  return out
}

/** Statements to turn `orig` into `edited`, in an order that avoids dependency errors. */
function alterTable(ctx: DdlContext, orig: TableDesign, edited: TableDesign, warnings: string[], errors: string[]): string[] {
  const { kind } = ctx
  const q = quoter(kind)
  const ref = tableRef(ctx, orig.name)
  const out: string[] = []

  const origByName = new Map(orig.columns.map((c) => [c.name, c]))
  const kept = edited.columns.filter((c) => c.originalName !== null && origByName.has(c.originalName))
  const keptOrigNames = new Set(kept.map((c) => c.originalName as string))
  const added = edited.columns.filter((c) => c.originalName === null)
  const dropped = orig.columns.filter((c) => !keptOrigNames.has(c.name))
  const renamed = kept.filter((c) => c.name !== c.originalName)
  const modified = kept.filter((c) => {
    const o = origByName.get(c.originalName as string)!
    return !o.locked && columnChanged(o, c)
  })

  // Map an edited index's columns back to the names they have in the database.
  const toOrig = new Map(kept.map((c) => [c.name, c.originalName as string]))
  const origIndexByName = new Map(orig.indexes.map((i) => [i.name, i]))
  const keptIndexNames = new Set<string>()
  const indexesToCreate: DesignIndex[] = []
  const indexesToDrop: DesignIndex[] = []
  for (const ix of edited.indexes) {
    const o = ix.originalName !== null ? origIndexByName.get(ix.originalName) : undefined
    if (!o) {
      indexesToCreate.push(ix)
      continue
    }
    keptIndexNames.add(o.name)
    if (o.locked) continue
    const cols = ix.columns.map((c) => toOrig.get(c) ?? `\0${c}`)
    const same = ix.name === o.name && ix.unique === o.unique && cols.length === o.columns.length && cols.every((c, i) => c === o.columns[i])
    if (!same) {
      indexesToDrop.push(o)
      indexesToCreate.push(ix)
    }
  }
  for (const o of orig.indexes) if (!keptIndexNames.has(o.name) && !o.locked) indexesToDrop.push(o)

  // Foreign keys, compared the same way (columns mapped back to their database names).
  const origFkByName = new Map(fksOf(orig).map((f) => [f.name, f]))
  const keptFkNames = new Set<string>()
  const fksToCreate: DesignForeignKey[] = []
  const fksToDrop: DesignForeignKey[] = []
  for (const fk of fksOf(edited)) {
    const o = fk.originalName !== null ? origFkByName.get(fk.originalName) : undefined
    if (!o) {
      fksToCreate.push(fk)
      continue
    }
    keptFkNames.add(o.name)
    if (o.locked) continue
    const cols = fk.columns.map((c) => toOrig.get(c) ?? `\0${c}`)
    const same =
      fk.name === o.name &&
      cols.length === o.columns.length &&
      cols.every((c, i) => c === o.columns[i]) &&
      refScope(ctx, fk) === refScope(ctx, o) &&
      fk.refTable === o.refTable &&
      fk.refColumns.length === o.refColumns.length &&
      fk.refColumns.every((c, i) => c === o.refColumns[i]) &&
      action(fk.onDelete) === action(o.onDelete) &&
      action(fk.onUpdate) === action(o.onUpdate)
    if (!same) {
      fksToDrop.push(o)
      fksToCreate.push(fk)
    }
  }
  for (const o of fksOf(orig)) if (!keptFkNames.has(o.name) && !o.locked) fksToDrop.push(o)
  if (kind === 'sqlite' && (fksToCreate.length || fksToDrop.length)) {
    errors.push('SQLite cannot add or drop foreign keys on an existing table; define them when the table is created.')
  }

  // Primary key: compare by database names so a rename alone is not a change.
  const origPk = pkOf(orig.columns).map((c) => c.name)
  const newPk = pkOf(edited.columns).map((c) => c.originalName ?? `\0${c.name}`)
  const pkChanged = origPk.length !== newPk.length || origPk.some((n, i) => n !== newPk[i])

  if (pkChanged && kind === 'sqlite') errors.push('SQLite cannot change the primary key of an existing table.')

  // 0. Foreign keys that must go (first: MySQL refuses to drop an index a foreign key still uses).
  if (kind !== 'sqlite') for (const fk of fksToDrop) out.push(dropFkDdl(ctx, ref, fk.name))

  // 1. Indexes that must go (before their columns do).
  for (const ix of indexesToDrop) out.push(dropIndexDdl(ctx, ref, ix.name))

  // 2. Primary key removal.
  if (pkChanged && origPk.length) {
    if (kind === 'mysql') out.push(`ALTER TABLE ${ref} DROP PRIMARY KEY`)
    else if (orig.pkName) out.push(`ALTER TABLE ${ref} DROP CONSTRAINT ${q(orig.pkName)}`)
    else errors.push('The existing primary key has no known name, so it cannot be dropped.')
  }

  // 3. Drop columns.
  for (const c of dropped) {
    if (kind === 'mssql' && c.defaultConstraint) out.push(`ALTER TABLE ${ref} DROP CONSTRAINT ${q(c.defaultConstraint)}`)
    out.push(`ALTER TABLE ${ref} DROP COLUMN ${q(c.name)}`)
    warnings.push(`Column "${c.name}" and all its data will be deleted.`)
  }

  // 4 + 5. Rename and modify.
  for (const c of kept) {
    const o = origByName.get(c.originalName as string)!
    const isRenamed = renamed.includes(c)
    const isModified = modified.includes(c)
    if (!isRenamed && !isModified) continue

    if (kind === 'mysql') {
      // CHANGE restates the whole definition and handles rename + modify in one go.
      out.push(`ALTER TABLE ${ref} ${isRenamed ? `CHANGE COLUMN ${q(o.name)}` : 'MODIFY COLUMN'} ${columnDef(kind, c)}`)
      continue
    }

    if (isRenamed) {
      if (kind === 'mssql') {
        const full = `${(ctx.schema ?? 'dbo').replace(/'/g, "''")}.${orig.name.replace(/'/g, "''")}.${o.name.replace(/'/g, "''")}`
        out.push(`EXEC sp_rename ${lit(full)}, ${lit(c.name)}, 'COLUMN'`)
      } else {
        out.push(`ALTER TABLE ${ref} RENAME COLUMN ${q(o.name)} TO ${q(c.name)}`)
      }
    }
    if (!isModified) continue

    if (kind === 'sqlite') {
      errors.push(`SQLite cannot change the type, nullability, default or auto-increment of existing column "${o.name}".`)
    } else if (kind === 'postgres') {
      const typeChanged = !sameType(o.type, c.type)
      // PostgreSQL refuses ALTER TYPE while a default exists that it cannot cast to the new type,
      // so drop the default first and put the (possibly new) one back afterwards.
      if (typeChanged && hasDefault(o)) out.push(`ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} DROP DEFAULT`)
      if (typeChanged) {
        out.push(`ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} TYPE ${c.type.trim()} USING ${q(c.name)}::${c.type.trim()}`)
        warnings.push(`Changing "${c.name}" to ${c.type.trim()} converts existing values and fails if any cannot be cast.`)
      }
      if (o.nullable !== c.nullable) out.push(`ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} ${c.nullable ? 'DROP' : 'SET'} NOT NULL`)
      if (typeChanged ? hasDefault(c) : norm(o.defaultValue) !== norm(c.defaultValue)) {
        out.push(hasDefault(c) ? `ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} SET DEFAULT ${norm(c.defaultValue)}` : `ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} DROP DEFAULT`)
      }
      if (o.autoIncrement !== c.autoIncrement) {
        out.push(`ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} ${c.autoIncrement ? 'ADD GENERATED BY DEFAULT AS IDENTITY' : 'DROP IDENTITY'}`)
      }
    } else if (kind === 'mssql') {
      if (o.autoIncrement !== c.autoIncrement) {
        errors.push(`SQL Server cannot add or remove IDENTITY on existing column "${o.name}".`)
        continue
      }
      // A default constraint blocks ALTER COLUMN, so drop it first and put it back after.
      if (o.defaultConstraint) out.push(`ALTER TABLE ${ref} DROP CONSTRAINT ${q(o.defaultConstraint)}`)
      if (!sameType(o.type, c.type) || o.nullable !== c.nullable) {
        out.push(`ALTER TABLE ${ref} ALTER COLUMN ${q(c.name)} ${c.type.trim()} ${c.nullable ? 'NULL' : 'NOT NULL'}`)
      }
      if (hasDefault(c)) out.push(`ALTER TABLE ${ref} ADD DEFAULT ${norm(c.defaultValue)} FOR ${q(c.name)}`)
    }
  }

  // 6. New columns.
  for (const c of added) {
    // T-SQL spells it ADD <column>; the others use ADD COLUMN.
    out.push(`ALTER TABLE ${ref} ${kind === 'mssql' ? 'ADD' : 'ADD COLUMN'} ${columnDef(kind, c)}`)
    if (!c.nullable && !hasDefault(c) && !c.autoIncrement) {
      warnings.push(`New NOT NULL column "${c.name}" has no default; adding it fails if the table already has rows.`)
    }
  }

  // 7. Primary key (re)creation.
  const pkCols = pkOf(edited.columns)
  if (pkChanged && pkCols.length && kind !== 'sqlite') {
    const cols = pkCols.map((c) => q(c.name)).join(', ')
    out.push(kind === 'mssql' ? `ALTER TABLE ${ref} ADD CONSTRAINT ${q(`PK_${orig.name}`)} PRIMARY KEY (${cols})` : `ALTER TABLE ${ref} ADD PRIMARY KEY (${cols})`)
  }

  // 8. Indexes that are new or were rebuilt.
  for (const ix of indexesToCreate) out.push(indexDdl(ctx, ref, ix))

  // 9. Foreign keys last, once every column, key and index they rely on exists.
  if (kind !== 'sqlite') for (const fk of fksToCreate) out.push(`ALTER TABLE ${ref} ADD ${fkClause(ctx, fk)}`)

  if (kind === 'mysql' && out.length > 1) {
    warnings.push('MySQL commits each DDL statement immediately; if one fails, the statements before it stay applied.')
  }
  return out
}

export function planDdl(ctx: DdlContext, original: TableDesign | null, edited: TableDesign): DdlPlan {
  const errors = validate(ctx, edited, original === null)
  const warnings: string[] = []
  if (errors.length) return { statements: [], warnings, errors }
  const statements = original === null ? createTable(ctx, edited) : alterTable(ctx, original, edited, warnings, errors)
  return { statements, warnings, errors }
}

/** DELETE FROM for every row of a table in the context's database/schema. */
export function deleteFromDdl(ctx: DdlContext, name: string): string {
  return `DELETE FROM ${tableRef(ctx, name)}`
}

/** DROP TABLE for a table in the context's database/schema. */
export function dropTableDdl(ctx: DdlContext, name: string): string {
  return `DROP TABLE ${tableRef(ctx, name)}`
}

/** Statements joined the way they are shown and run. */
export const formatDdl = (statements: string[]): string => statements.map((s) => `${s};`).join('\n\n')
